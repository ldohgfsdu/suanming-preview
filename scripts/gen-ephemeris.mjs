/**
 * scripts/gen-ephemeris.mjs — 程序化生成 miniprogram/lib/sunEphem.data.js
 *（高精度节气的 VSOP87 地球级数 + 1980 IAU 章动表）。
 *
 * 数据来源（权威、代码生成，杜绝手抄）：
 *   - VSOP87B.ear（IMCCE 官方）：地球日心黄道 J2000 球坐标级数（L=变量1，R=变量3）。
 *   - nutation.go 的 table22A：Meeus ch.22 1980 IAU 63 项章动（D/M/N/F/Ω, s0,s1, c0,c1）。
 *
 * 运行： node scripts/gen-ephemeris.mjs
 * 产物： miniprogram/lib/sunEphem.data.js （ESM，导出 L/R/NUT）。
 * 若本地缓存（.tmp/VSOP87B.ear 等）缺失，从网络拉取；网络不可用时可在有网环境先跑本脚本并提交产物。
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'miniprogram', 'lib', 'sunEphem.data.js');
const CACHE = path.join(ROOT, '.tmp');

const EAR = path.join(CACHE, 'VSOP87B.ear');
const NUTGO = path.join(CACHE, 'nutation.go');

// ---------- fetch helper ----------
function curl(url, dest, retries = 4) {
  try { execFileSync('curl', ['-s', '-L', '--retry', String(retries), '--max-time', '30', '-o', dest, url]); }
  catch { throw new Error('download failed: ' + url); }
  if (!existsSync(dest)) throw new Error('empty download: ' + url);
}
function ensure(url, dest) {
  if (existsSync(dest)) return;
  const MIRRORS = [url];
  let last;
  for (const u of MIRRORS) try { curl(u, dest); return; } catch (e) { last = e; }
  throw last;
}
const VSOP_URL = 'ftp://ftp.imcce.fr/pub/ephem/planets/vsop87/VSOP87B.ear';
const NUT_URL  = 'https://raw.githubusercontent.com/soniakeys/meeus/master/v3/nutation/nutation.go';

// ---------- VSOP87B parse ----------
function buildSeries(linesArr, want) {
  const series = { '1': {}, '3': {} };
  let n = 0;
  while (n < linesArr.length) {
    const line = linesArr[n];
    if (line.length < 132) { n++; continue; }
    const c = line[41];
    if (want.includes(c)) {
      const p = line.charCodeAt(59) - 48;
      const cnt = parseInt(line.substring(60, 67).trim(), 10);
      n++;
      const terms = [];
      for (let t = 0; t < cnt && n < linesArr.length; t++, n++) {
        const tl = linesArr[n];
        terms.push([
          parseFloat(tl.substring(79, 97).trim()),
          parseFloat(tl.substring(98, 111)),
          parseFloat(tl.substring(111, 131).trim()),
        ]);
      }
      series[c][p] = terms;
      continue;
    }
    n++;
  }
  return series;
}
// ---------- nutation parse ----------
function parseNutation(src) {
  const nut = [];
  let inTab = false;
  for (const ln of src.split('\n')) {
    const t = ln.trim();
    if (t.startsWith('var table22A')) { inTab = true; continue; }
    if (inTab) {
      if (t === '}') break;
      if (t.startsWith('{') && t.endsWith('},')) {
        const v = t.slice(1, -2).split(',').map(x => x.trim());
        nut.push([+v[0], +v[1], +v[2], +v[3], +v[4], +v[5], +v[6], +v[7], +v[8]]);
      }
    }
  }
  return nut;
}

// ---------- run ----------
ensure(VSOP_URL, EAR);
ensure(NUT_URL, NUTGO);

const EAR_SRC = String(readFileSync(EAR));
const S = buildSeries(EAR_SRC.split('\n'), ['1', '3']);
const L = S['1'], R = S['3'];
const nut = parseNutation(readFileSync(NUTGO, 'utf8'));

function emitSeries(name, series) {
  let out = `const ${name} = {\n`;
  for (const p of Object.keys(series)) {
    const terms = series[p];
    const flat = new Array(terms.length * 3);
    for (let i = 0; i < terms.length; i++) {
      flat[i*3] = terms[i][0]; flat[i*3+1] = terms[i][1]; flat[i*3+2] = terms[i][2];
    }
    out += `  ${p}: [${flat.map(x => x.toPrecision(14)).join(',')}],\n`;
  }
  return out + `};\n`;
}

const js = `// Generated by scripts/gen-ephemeris.mjs from VSOP87B.ear (IMCCE) + Meeus ch.22 nutation.
// Solar apparent ecliptic longitude (geocentric, equinox+equinox of date).
'use strict';

${emitSeries('L', L)}
${emitSeries('R', R)}

// NUTATION rows [D,M,N,F,Ω, s0,s1] (s0/s1 in 0.0001 arcsec)
const NUT = [\n${nut.map(r => `  [${r.join(',')}],`).join('\n')}\n];\n\nexport { L, NUT, R };\n`;
writeFileSync(OUT, js);
console.log(`wrote ${OUT}  (${js.length} bytes), L terms=${Object.values(L).reduce((a,t)=>a+t.length,0)}, R terms=${Object.values(R).reduce((a,t)=>a+t.length,0)}, nutation=${nut.length}`);
