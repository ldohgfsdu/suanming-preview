// ─────────────────────────── 查询辅助 ───────────────────────────

export function cultureCategoryOf(catId) {
  return CULTURE_CATEGORIES.find((c) => c.id === catId) || null;
}

export function cultureEntryById(id) {
  return CULTURE_ENTRIES.find((e) => e.id === id) || null;
}

/** 解析条目的关联概念（relations 只存 id，展示时需要名称） */
export function cultureRelated(entry) {
  if (!entry || !Array.isArray(entry.relations)) return [];
  const out = [];
  for (const rel of entry.relations) {
    const target = cultureEntryById(rel.id);
    if (target) out.push({ id: target.id, name: target.name, text: rel.text, glyph: target.glyph || '' });
  }
  return out;
}

/**
 * 档案页「就地科普」面板的装配：条目 → 页面上要显示的最小字段集。
 * 不返回 sections/attrs 等长字段——就地展开只给摘要与定义全文，
 * 更深的内容由「读完整科普」跳详情页。
 */
export function culturePanelOf(id) {
  const entry = cultureEntryById(id);
  if (!entry) return null;
  return {
    id: entry.id,
    name: entry.name,
    glyph: entry.glyph || '',
    summary: entry.summary,
    definition: entry.definition,
  };
}

/**
 * 「就地科普」面板的开关语义（纯函数，两个页面共用一份，避免逻辑漂移）：
 *   - 再点同一概念 → 收起；点另一概念 → 切换为该条目的面板
 *   - 空 id 或解析不到的 id → 返回 null，调用方应保持原状（防死链）
 * 返回 null 与返回「收起态」是两回事：前者什么都不做，后者才是合法的新状态。
 */
export function cultureToggle(currentId, tappedId) {
  if (!tappedId) return null;
  if (tappedId === currentId) return { cultureOpenId: '', cultureOpen: null };
  const panel = culturePanelOf(tappedId);
  if (!panel) return null;
  return { cultureOpenId: panel.id, cultureOpen: panel };
}

// 检索字段权重：名称 > 关键词 > 摘要 > 分类 > 正文
const SEARCH_FIELDS = [
  { key: 'name', weight: 12 },
  { key: 'keywords', weight: 9 },
  { key: 'summary', weight: 6 },
  { key: 'glyph', weight: 4 },
  { key: 'definition', weight: 3 },
  { key: 'origin', weight: 3 },
];

function fieldText(entry, key) {
  if (key === 'keywords') return (entry.keywords || []).join(' ');
  return String(entry[key] || '');
}

function fullText(entry) {
  const parts = [entry.name, entry.summary, entry.definition, entry.origin, entry.glyph || ''];
  for (const s of entry.sections || []) parts.push(s.title, s.body);
  for (const a of entry.attrs || []) parts.push(a.k, a.v);
  if (entry.table) {
    parts.push(...entry.table.head);
    for (const row of entry.table.rows) parts.push(...row);
  }
  return parts.join(' ').toLowerCase();
}

/**
 * 文化知识检索：多个关键词以空格分隔，按「与」语义组合（每个词都必须命中），
 * 命中字段越靠前权重越高；空关键词返回全部。返回按相关度降序的条目数组。
 */
export function cultureSearch(keyword) {
  const terms = String(keyword || '')
    .trim()
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean);
  if (!terms.length) return CULTURE_ENTRIES.slice();

  const scored = [];
  for (const entry of CULTURE_ENTRIES) {
    let total = 0;
    let matchedAll = true;
    for (const term of terms) {
      let best = 0;
      for (const f of SEARCH_FIELDS) {
        if (fieldText(entry, f.key).toLowerCase().includes(term)) { best = Math.max(best, f.weight); }
      }
      if (!best) best = fullText(entry).includes(term) ? 1 : 0;
      if (!best) { matchedAll = false; break; }
      total += best;
    }
    if (matchedAll) scored.push({ entry, total });
  }
  scored.sort((a, b) => (b.total - a.total) || (a.entry.name.localeCompare(b.entry.name, 'zh')));
  return scored.map((s) => s.entry);
}
