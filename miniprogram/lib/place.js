/**
 * 查询某省某市（区县可选）的坐标。
 * @returns { { prov, city, district, lng, lat } | null }
 *   lng 东经正、lat 北纬正；district 为区县名；找不到该市返回 null。
 * 若省 / 市存在但区县不在表内，区县回退为该市名。
 */
export function locateProvinceCity(prov, city, district) {
  const p = DATA[prov];
  if (!p) return null;
  const row = p.find((c) => c[0] === city);
  if (!row) return null;
  const [, , lat, districts] = row;
  const lng = row[1];
  const d = district && districts.indexOf(district) >= 0 ? district : city;
  return { prov, city, district: d, lng, lat };
}

/** 省下列出该省的所有城市名。 */
export function cityNames(prov) {
  const p = DATA[prov];
  return p ? p.map((c) => c[0]) : [];
}

/** 省 / 市下列出可选区县名（缺省则只用市本身）。 */
export function districtNames(prov, city) {
  const p = DATA[prov];
  if (!p) return [];
  const row = p.find((c) => c[0] === city);
  return row && row[3] ? row[3] : [];
}